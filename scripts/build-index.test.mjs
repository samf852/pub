import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import {
  collectPages,
  pageEntry,
  pageHref,
  renderIndex,
} from './build-index.mjs';

test('directory pages link to a trailing-slash path', () => {
  assert.equal(pageHref('pages/hello/index.html'), 'pages/hello/');
});

test('flat pages keep the html file in the path', () => {
  assert.equal(pageHref('pages/notes/week 1.html'), 'pages/notes/week%201.html');
});

test('frontmatter title and description win over tags', () => {
  const entry = pageEntry(`<!DOCTYPE html>
<!--
title: From the comment
description: Short label
-->
<title>Tag title</title>
<meta name="description" content="Tag description">
`, 'pages/hello/index.html');
  assert.deepEqual(entry, {
    title: 'From the comment',
    description: 'Short label',
    href: 'pages/hello/',
  });
});

test('title and meta description are used when frontmatter is absent', () => {
  const entry = pageEntry(`<title>Hello &amp; co</title>
<meta content="A note" name="description">`, 'pages/my-note.html');
  assert.equal(entry.title, 'Hello & co');
  assert.equal(entry.description, 'A note');
  assert.equal(entry.href, 'pages/my-note.html');
});

test('missing labels fall back to the file name', () => {
  const entry = pageEntry('<p>No title</p>', 'pages/field-notes/index.html');
  assert.equal(entry.title, 'Field notes');
  assert.equal(entry.href, 'pages/field-notes/');
});

test('collectPages lists every html file and renderIndex links them', async () => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'pub-pages-'));
  try {
    await mkdir(path.join(dir, 'hello'), { recursive: true });
    await writeFile(path.join(dir, 'hello', 'index.html'), '<title>Hello</title>');
    await writeFile(path.join(dir, 'later.html'), '<!--\ntitle: Later\n-->');
    const pages = await collectPages(dir);
    assert.deepEqual(pages.map((page) => page.href), ['pages/hello/', 'pages/later.html']);
    const html = renderIndex(pages);
    assert.match(html, /href="pages\/hello\/"/);
    assert.match(html, /href="pages\/later\.html"/);
    assert.match(html, /Generated by scripts\/build-index\.mjs/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('titles are escaped in the generated index', () => {
  const html = renderIndex([{
    title: '<script>',
    description: 'a & b',
    href: 'pages/x.html',
  }]);
  assert.match(html, /&lt;script&gt;/);
  assert.doesNotMatch(html, /<script>/);
  assert.match(html, /a &amp; b/);
});
