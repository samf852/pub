import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pagesDir = path.join(root, 'pages');
const indexPath = path.join(root, 'index.html');

export function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

export function decodeHtml(value) {
  return String(value)
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&amp;', '&');
}

function attr(tag, name) {
  const match = tag.match(new RegExp(`\\b${name}\\s*=\\s*("([^"]*)"|'([^']*)')`, 'i'));
  if (!match) return '';
  return match[2] ?? match[3] ?? '';
}

export function readFrontmatter(html) {
  const found = {};
  const comment = /<!--([\s\S]*?)-->/g;
  let match;
  const head = html.slice(0, 8000);
  while ((match = comment.exec(head))) {
    for (const line of match[1].split('\n')) {
      const kv = line.match(/^\s*(title|description)\s*:\s*(.*)$/i);
      if (!kv) continue;
      const key = kv[1].toLowerCase();
      if (found[key] == null) found[key] = kv[2].trim();
    }
    if (found.title || found.description) break;
  }
  return found;
}

export function metaDescription(html) {
  const tags = html.match(/<meta\b[^>]*>/gi) || [];
  for (const tag of tags) {
    if (attr(tag, 'name').toLowerCase() !== 'description') continue;
    return decodeHtml(attr(tag, 'content')).replace(/\s+/g, ' ').trim();
  }
  return '';
}

export function titleFromTag(html) {
  const match = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  if (!match) return '';
  return decodeHtml(match[1]).replace(/\s+/g, ' ').trim();
}

export function humanize(relPosix) {
  const base = relPosix.endsWith('/index.html')
    ? relPosix.slice(0, -'/index.html'.length).split('/').filter(Boolean).pop()
    : path.posix.basename(relPosix, '.html');
  const words = (base || 'page').replace(/[-_]+/g, ' ').trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

export function pageHref(relPosix) {
  const isDirectory = relPosix.endsWith('/index.html');
  const trimmed = isDirectory ? relPosix.slice(0, -'index.html'.length) : relPosix;
  const encoded = trimmed.split('/').filter(Boolean).map(encodeURIComponent).join('/');
  return isDirectory ? `${encoded}/` : encoded;
}

export function pageEntry(html, relPosix) {
  const frontmatter = readFrontmatter(html);
  const title = frontmatter.title || titleFromTag(html) || humanize(relPosix);
  const description = frontmatter.description || metaDescription(html) || '';
  return {
    title,
    description,
    href: pageHref(relPosix),
  };
}

async function walkHtml(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }

  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walkHtml(full));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith('.html')) {
      files.push(full);
    }
  }
  return files;
}

export async function collectPages(dir) {
  const files = await walkHtml(dir);
  const pages = [];
  for (const file of files) {
    const html = await readFile(file, 'utf8');
    const rel = path.relative(dir, file).split(path.sep).join('/');
    pages.push(pageEntry(html, `pages/${rel}`));
  }
  pages.sort((a, b) => a.title.localeCompare(b.title, 'en', { sensitivity: 'base' })
    || a.href.localeCompare(b.href));
  return pages;
}

function renderItem(page) {
  const description = page.description
    ? `\n        <p>${escapeHtml(page.description)}</p>`
    : '';
  return `      <li>
        <a href="${escapeHtml(page.href)}">
          <span class="label">${escapeHtml(page.title)}</span>
          <span class="path">${escapeHtml(page.href)}</span>
        </a>${description}
      </li>`;
}

export function renderIndex(pages) {
  const body = pages.length
    ? `<ul class="page-list">\n${pages.map(renderItem).join('\n')}\n    </ul>`
    : '<p class="empty">No pages yet. Add an HTML file under <code>pages/</code> and run <code>npm run build</code>.</p>';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>pub · samf852</title>
  <meta name="description" content="Pages published by samf852.">
  <link rel="stylesheet" href="assets/site.css">
</head>
<body>
  <!-- Generated by scripts/build-index.mjs. Do not edit by hand. -->
  <div class="wrap">
    <p class="eyebrow">samf852</p>
    <h1>pub</h1>
    <p class="lede">A hub of HTML pages. Each one keeps its own address.</p>
    ${body}
    <footer>
      <p>Generated by <code>npm run build</code>. Add a file under <code>pages/</code>, then rebuild locally or push to <code>main</code> and let GitHub Actions rebuild this list.</p>
    </footer>
  </div>
</body>
</html>
`;
}

async function main() {
  const pages = await collectPages(pagesDir);
  await writeFile(indexPath, renderIndex(pages));
  console.log(`Wrote index.html (${pages.length} page${pages.length === 1 ? '' : 's'})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
